void check_cuda(cudaError_t status, const char* call) {
  if (status == cudaSuccess) return;
  throw Error(std::string(call) + ": " + cudaGetErrorName(status));
}

void check_cudnn(cudnnStatus_t status, const char* call) {
  if (status == CUDNN_STATUS_SUCCESS) return;
  const char* name = cudnn_name(status);
  if (name) throw Error(std::string(call) + ": " + name);
  throw Error(std::string(call) + ": " + std::to_string(static_cast<int>(status)));
}

void check_cublas(cublasStatus_t status, const char* call) {
  if (status == CUBLAS_STATUS_SUCCESS) return;
  const char* name = cublasGetStatusName(status);
  throw Error(std::string(call) + ": " + (name ? name : std::to_string(static_cast<int>(status))));
}

